'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { toWebVtt } = require('../js/transcripts.js');

function compileLessonTranscripts(root) {
  const readJson = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  const manifest = readJson('content/lesson-transcripts.json');
  const catalog = readJson('content/lesson-videos.json');
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.transcripts)) throw new Error('Invalid lesson transcript manifest.');
  const videoIds = new Set(catalog.videos.map(video => video.id));
  const mappedVideos = new Set(), mappedFiles = new Set();
  const passages = Object.create(null);
  for (const item of manifest.transcripts) {
    if (!videoIds.has(item.videoId) || mappedVideos.has(item.videoId)) throw new Error(`Invalid or duplicate transcript video mapping: ${item.videoId}`);
    if (typeof item.file !== 'string' || path.basename(item.file) !== item.file || !/^[A-Za-z0-9._-]+\.srt$/i.test(item.file) || mappedFiles.has(item.file)) {
      throw new Error(`Invalid or duplicate transcript filename: ${item.file}`);
    }
    const source = path.join(root, 'transcript', item.file);
    if (!fs.existsSync(source)) throw new Error(`Mapped transcript is missing: ${item.file}`);
    passages[item.file.replace(/\.srt$/i, '.vtt')] = toWebVtt(fs.readFileSync(source, 'utf8'));
    mappedVideos.add(item.videoId);
    mappedFiles.add(item.file);
  }
  return passages;
}

function writeLessonTranscripts(root) {
  const passages = compileLessonTranscripts(root);
  const directory = path.join(root, 'functions', '_generated');
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, 'lesson-transcripts.cjs'), "'use strict';\n// Generated by npm run build; server-only.\nmodule.exports = " + JSON.stringify(passages) + ';\n');
  // Remove only old generated WebVTT assets, never source SRTs or other files.
  const oldPublicDirectory = path.join(root, 'dist', 'transcript');
  if (fs.existsSync(oldPublicDirectory)) {
    for (const entry of fs.readdirSync(oldPublicDirectory, { withFileTypes: true })) {
      if (entry.isFile() && /\.vtt$/i.test(entry.name)) fs.unlinkSync(path.join(oldPublicDirectory, entry.name));
    }
    if (!fs.readdirSync(oldPublicDirectory).length) fs.rmdirSync(oldPublicDirectory);
  }
  return passages;
}

module.exports = { compileLessonTranscripts, writeLessonTranscripts };
